def calcular_cantidad_a_pedir(stock_actual, stock_minimo):
    """Devuelve la cantidad exacta a pedir para un artículo."""
    if stock_actual < stock_minimo:
        return stock_minimo - stock_actual
    return 0


def mostrar_informe(inventario):
    """Recorre la matriz y muestra el nombre y la cantidad a pedir."""
    print("=" * 50)
    print("INFORME DE REABASTECIMIENTO")
    print("=" * 50)
    print(f"{'Artículo':<25}{'Cantidad a pedir':>20}")
    print("-" * 50)

    for fila in inventario:
        nombre = fila[1]
        stock_actual = fila[2]
        stock_minimo = fila[3]
        cantidad = calcular_cantidad_a_pedir(stock_actual, stock_minimo)
        print(f"{nombre:<25}{cantidad:>20}")


def main():
    # Matriz de inventario (6 artículos)
    inventario = [
        ["A001", "Teclado", 12, 20],
        ["A002", "Mouse", 30, 15],
        ["A003", "Monitor", 5, 10],
        ["A004", "Cable HDMI", 8, 8],
        ["A005", "Memoria USB", 0, 25],
        ["A006", "Impresora", 4, 3],
    ]

    mostrar_informe(inventario)


main()